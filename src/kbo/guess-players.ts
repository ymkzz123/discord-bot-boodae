export function pickRandomKboPlayer(
  nextIndex: (maxExclusive: number) => number = randomInt,
): KboGuessPlayer {
  const index = nextIndex(KBO_GUESS_PLAYERS.length);
  const name = KBO_GUESS_PLAYERS[index];
  if (!name) throw new Error("KBO player selector returned an invalid index");
  return { name, team: KBO_GUESS_PLAYER_TEAMS[name] };
}
